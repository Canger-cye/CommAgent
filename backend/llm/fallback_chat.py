"""离线自由对话回退（无 API Key / 网络失败时）。"""
from __future__ import annotations

import re

_PATTERNS: list[tuple[str, list[str]]] = [
    (
        "嗨～我是 CommAgent。想算指标、查问题，或者随便聊聊都行。",
        ["你好", "您好", "hi", "hello", "嗨", "哈喽", "在吗", "在么", "早上好", "下午好", "晚上好"],
    ),
    (
        "不客气！还有要跑的指令随时喊我。",
        ["谢谢", "感谢", "多谢", "辛苦了", "辛苦"],
    ),
    (
        "好嘞，先这样。有告警或覆盖问题再来找我～",
        ["再见", "拜拜", "晚安", "下次见", "走了"],
    ),
    (
        "我是 CommAgent：面向 6G 通感算智的运维台。链路预算、波束赋形、干扰分析、根因诊断、功率优化、出报告都能干，也接闲聊。",
        ["你是谁", "你叫什么", "介绍下你", "介绍一下你", "你是什么", "你是ai", "你是机器人"],
    ),
    (
        "为什么 SINR 从不去夜店？——因为旁边全是干扰。",
        ["笑话", "逗我", "讲个笑话", "说个笑话"],
    ),
    (
        "我也就绪得挺稳定的。你要是累了，咱们先歇口气再算。",
        ["累", "疲惫", "好困", "心情", "开心", "难过", "无聊", "emo"],
    ),
    (
        "这个话题离我的专业有点远，不过陪你聊两句没问题。要是想干活，随时丢个「链路预算」或「诊断」过来。",
        ["天气", "吃饭", "睡觉", "电影", "游戏", "音乐", "对象"],
    ),
]


def offline_reply(text: str) -> str:
    t = (text or "").strip()
    low = t.lower()

    for reply, kws in _PATTERNS:
        if any(k in low or k in t for k in kws):
            return reply

    if re.search(r"[？?]|吗|呢|怎么|什么|为什么|如何", t):
        return (
            "这个问题我离线模式下只能聊个大概。"
            "你可以先说个专业需求（比如「200m 的链路预算」），"
            "或者到右上角「模型设置」接上大模型，就能像平时一样多轮聊天了。"
        )

    return "嗯嗯，有收到。想干活的话丢个指令过来，想聊天也行～"
